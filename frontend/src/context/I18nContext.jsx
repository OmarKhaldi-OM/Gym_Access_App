const dictionaries = Object.fromEntries(
  Object.keys(messages).map((language) => [language, { ...messages[language], ...contentMessages[language], ...additionalMessages[language] }]),
)
const allKeys = Object.keys(dictionaries.en)
if (Object.values(dictionaries).some((dictionary) => allKeys.some((key) => dictionary[key] === undefined))) {
  throw new Error('Translation catalogs must define the same keys for English, French, and Arabic.')
}

function getInitialLanguage() {
  const saved = localStorage.getItem(STORAGE_KEY)
  return messages[saved] ? saved : 'fr'
}

export function I18nProvider({ children }) {
  const [language, setLanguageState] = useState(getInitialLanguage)
  const setLanguage = (nextLanguage) => {
    if (dictionaries[nextLanguage]) setLanguageState(nextLanguage)
  }
  const direction = language === 'ar' ? 'rtl' : 'ltr'
  const value = useMemo(() => ({ language, direction, messages: dictionaries[language], setLanguage }), [language, direction])

  useLayoutEffect(() => {
    document.documentElement.lang = language
    document.documentElement.dir = direction
    document.documentElement.dataset.language = language
    localStorage.setItem(STORAGE_KEY, language)
  }, [language, direction])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) throw new Error('useI18n doit être utilisé dans un I18nProvider')
  return context
}

export function useT() {
  const { messages } = useI18n()
  return useCallback(
    (key, fallback = key) => messages[translationAliases[key] || key] || fallback,
    [messages],
  )
}
